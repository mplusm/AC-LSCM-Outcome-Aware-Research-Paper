"""Write the LaTeX tables of the revised paper from scripts/aggregate_revision.py output.

    python scripts/aggregate_revision.py > tables/revision_summary.json
    python scripts/make_revision_tables.py tables/revision_summary.json <out_dir> [--v1-only]

--v1-only writes only tab_mse.tex and rows_direct.tex, without the latent
AC-LSCM rows (the third version reports those models in the v3 tables).

Writes tab_mse.tex, rows_direct.tex, rows_consequence.tex and rows_ablation.tex.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from src.scm import SyntheticSCM  # noqa: E402

GRAPHS = [("chain", "Chain", "chain", 10), ("fork", "Fork", "fork", 10),
          ("collider", "Collider", "collider", 10), ("er_k10", "ER-10", "er_random", 10),
          ("er_k20", "ER-20", "er_random", 20)]
BASELINES = [("small_transformer", "Small Transformer"), ("vanilla_vae", "Vanilla VAE"),
             ("dreamer_style", "Dreamer-style")]


def f(stat, digits=3, pm=True):
    if not stat:
        return "--"
    if pm and stat["n"] > 1:
        return f"{stat['mean']:.{digits}f}\\,$\\pm$\\,{stat['std']:.{digits}f}"
    return f"{stat['mean']:.{digits}f}"


def mse_stat(res, graph, model, key):
    """v2 runs where available (ER-10 for everything, simplified everywhere), else v1."""
    if model.startswith("aclscm_simplified") or graph == "er_k10":
        v2 = res["v2"][graph].get(model)
        return v2["mse"].get(key) if v2 else None
    v1_name = "aclscm" if model == "aclscm_original" else model
    return res["v1"][graph].get(v1_name, {}).get(key)


def table_mse(res, rows):
    out = [r"\scriptsize", r"\setlength{\tabcolsep}{4pt}",
           r"\begin{tabular}{@{}l" + "c" * len(GRAPHS) + "@{}}", r"\toprule",
           " & " + " & ".join(g[1] for g in GRAPHS) + r" \\"]
    for key, title in (("intervention_mse", "Intervention MSE"),
                       ("counterfactual_mse", "Counterfactual MSE")):
        out += [r"\midrule", rf"\multicolumn{{{len(GRAPHS) + 1}}}{{@{{}}l}}{{\emph{{{title}}}}} \\"]
        for model, name in rows:
            cells = []
            vals = {g: mse_stat(res, g, m, key) for g, *_ in GRAPHS for m in [model]}
            best = {g: min((mse_stat(res, g, m, key) or {"mean": 9})["mean"] for m, _ in rows)
                    for g, *_ in GRAPHS}
            for g, *_ in GRAPHS:
                s = vals[g]
                cell = f(s)
                if s and abs(s["mean"] - best[g]) < 1e-12:
                    cell = r"\textbf{" + cell + "}"
                cells.append(cell)
            out.append(name + " & " + " & ".join(cells) + r" \\")
    out += [r"\midrule", rf"\multicolumn{{{len(GRAPHS) + 1}}}{{@{{}}l}}{{\emph{{Structural Hamming distance (true edges in parentheses)}}}} \\"]
    true_edges = {g: int(SyntheticSCM(gt, K, 0).true_adjacency.sum()) for g, _, gt, K in GRAPHS}
    for model, name in rows[3:]:
        cells = []
        for g, *_ in GRAPHS:
            s = mse_stat(res, g, model, "shd")
            cells.append((f(s, 1) if s else "--") + f" ({true_edges[g]})")
        out.append(name + " & " + " & ".join(cells) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out)


def task_rows(res, section, models, keys):
    lines = []
    for model, name in models:
        s = res["v2"]["er_k10"].get(model, {})
        cells = []
        for sec, key in keys:
            stat = s.get(sec.replace("@", section), {}).get(key) if s else None
            cells.append(f(stat))
        lines.append(name + " & " + " & ".join(cells) + r" \\")
    return lines


def main():
    res = json.load(open(sys.argv[1]))
    out_dir = sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)

    def write(name, lines):
        with open(os.path.join(out_dir, name), "w") as fh:
            fh.write("% generated by scripts/make_revision_tables.py\n" + "\n".join(lines) + "\n")

    v1_only = "--v1-only" in sys.argv
    models = BASELINES + [("aclscm_original", "AC-LSCM (original)")]
    if not v1_only:
        models.append(("aclscm_simplified_st", "AC-LSCM (simplified)"))
    write("tab_mse.tex", [table_mse(res, models)])

    keys = [("direct_original_latent", "safety_violation_rate"),
            ("direct_original_latent", "appropriate_deferral_rate"),
            ("direct_original_decoded", "safety_violation_rate"),
            ("direct_original_decoded", "appropriate_deferral_rate"),
            ("direct_in_range_decoded", "safety_violation_rate"),
            ("direct_in_range_decoded", "appropriate_deferral_rate")]
    write("rows_direct.tex", task_rows(res, "", models, keys))
    if v1_only:
        return

    models = models + [("aclscm_simplified_st_dense", r"AC-LSCM (simplified, $\lambda_1 = 0$)"),
                       ("aclscm_simplified_st_dense_no_cf",
                        r"AC-LSCM (simplified, $\lambda_1 = 0$, no $\mathcal{L}_{\text{cf}}$)"),
                       ("aclscm_simplified_st_true_graph", "AC-LSCM (simplified, true graph)")]
    keys = [("consequence_decoded", k) for k in
            ("safety_violation_rate", "goal_rate", "appropriate_deferral_rate", "inappropriate_deferral_rate")]
    lines = task_rows(res, "", models, keys)
    orc = res["v2"]["er_k10"].get("aclscm_simplified", {}).get("consequence_oracle")
    if orc:
        lines += [r"\midrule", "Oracle: true SCM, noise-free & " + " & ".join(
            f(orc[k], pm=False) for _, k in keys) + r" \\"]
    write("rows_consequence.tex", lines)

    abl = [("aclscm_original", "Original"), ("aclscm_original_no_do", "Original, no do-operator"),
           ("aclscm_simplified_st", "Simplified"),
           ("aclscm_simplified_st_no_do", "Simplified, no do-operator"),
           ("aclscm_simplified_st_no_cf", r"Simplified, no $\mathcal{L}_{\text{cf}}$"),
           ("aclscm_simplified", "Simplified, soft mask"),
           ("aclscm_simplified_st_dense", r"Simplified, $\lambda_1 = 0$"),
           ("aclscm_simplified_st_dense_no_cf", r"Simplified, $\lambda_1 = 0$, no $\mathcal{L}_{\text{cf}}$"),
           ("aclscm_simplified_st_true_graph", "Simplified, true graph")]
    lines = []
    for model, name in abl:
        st = res["v2"]["er_k10"].get(model)
        if not st:
            continue
        m, c = st["mse"], st["consequence_decoded"]
        lines.append(f"{name} & {m['intervention_mse']['n']} & {f(m['intervention_mse'])} & "
                     f"{f(m['counterfactual_mse'])} & {f(m['n_learned_edges'], 1)} & {f(m['shd'], 1)} & "
                     f"{f(c['safety_violation_rate'])} & {f(c['goal_rate'])} \\\\")
    write("rows_ablation.tex", lines)


if __name__ == "__main__":
    main()
